#!/usr/bin/env python3
"""gen_ss_creds.py - the Pico's built-in ScreenScraper developer credentials, for its box art.

Reads key=value lines (devid=, devpassword=, softname=) from a file that is never committed:
the first of ss_creds.local.txt at the repository's top, or the one GammaOS Nano keeps
(frameworks/base/cmds/gammaos-nano/screenscraper_dev.local.txt in the GammaOS tree). Writes
emu/gba/pico_ss_creds.gen.h (also never committed: .gitignore) holding only the values XOR-masked
with a random key made on every run, each value cut in two, so no readable form reaches the
repository or the image. Without the file the build has no ScreenScraper and uses the libretro
thumbnails only. Nothing is printed but where the values came from.

usage: gen_ss_creds.py [creds.txt]
"""
import os
import secrets
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
OUT = os.path.join(REPO, "emu", "gba", "pico_ss_creds.gen.h")
CANDIDATES = [
    os.path.join(REPO, "ss_creds.local.txt"),
    "/work/GammaOSNextDistribution-A14/frameworks/base/cmds/gammaos-nano/screenscraper_dev.local.txt",
]


def read(path):
    vals = {}
    for line in open(path, encoding="utf-8"):
        line = line.strip()
        if line and not line.startswith("#") and "=" in line:
            k, _, v = line.partition("=")
            vals[k.strip()] = v.strip()
    return vals


def masked(name, value, key):
    raw = value.encode("utf-8")
    x = bytes(b ^ key[i % len(key)] for i, b in enumerate(raw))
    half = (len(x) + 1) // 2
    out = []
    for part, chunk in (("a", x[:half]), ("b", x[half:])):
        body = ", ".join("0x%02x" % c for c in chunk) or "0"
        out.append("static const unsigned char %s_%s[] = { %s };" % (name, part, body))
    out.append("#define %s_LEN %d" % (name.upper(), len(raw)))
    return out


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else next((p for p in CANDIDATES if os.path.exists(p)), None)
    if not src or not os.path.exists(src):
        sys.exit("no credentials file (ss_creds.local.txt): the build will use the libretro thumbnails only")
    v = read(src)
    devid, devpw = v.get("devid", ""), v.get("devpassword", "")
    soft = v.get("softname", "") or "gammaos-pico"
    if not devid or not devpw:
        sys.exit("the credentials file needs devid= and devpassword=")
    key = secrets.token_bytes(32)
    lines = [
        "/* generated by tools/ayaneo/pico_current/gen_ss_creds.py: never commit (.gitignore) */",
        "#ifndef PICO_SS_CREDS_GEN_H",
        "#define PICO_SS_CREDS_GEN_H",
        "static const unsigned char ss_key[] = { %s };" % ", ".join("0x%02x" % c for c in key),
    ]
    lines += masked("ss_id", devid, key)
    lines += masked("ss_pw", devpw, key)
    lines += masked("ss_soft", soft, key)
    lines.append("#endif")
    with open(OUT, "w", encoding="ascii") as f:
        f.write("\n".join(lines) + "\n")
    os.chmod(OUT, 0o600)
    print("ScreenScraper credentials from %s -> %s (masked)" % (src, os.path.relpath(OUT, REPO)))


if __name__ == "__main__":
    main()
