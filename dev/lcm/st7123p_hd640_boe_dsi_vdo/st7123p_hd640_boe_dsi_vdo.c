static void push_table(struct LCM_setting_table *table, unsigned int count,
		       unsigned char force_update)
{
	unsigned int i;

	for (i = 0; i < count; i++) {
		unsigned char cmd = table[i].cmd;

		switch (cmd) {
		case REGFLAG_DELAY:
			MDELAY(table[i].count);
			break;
		case REGFLAG_END_OF_TABLE:
			break;
		default:
			dsi_set_cmdq_V2(cmd, table[i].count, table[i].para_list,
					force_update);
		}
	}
}

#ifdef BUILD_LK
static void lcm_gpio_output(unsigned int gpio, unsigned int level)
{
	mt_set_gpio_mode(gpio, GPIO_MODE_00);
	mt_set_gpio_dir(gpio, GPIO_DIR_OUT);
	mt_set_gpio_out(gpio, level ? GPIO_OUT_ONE : GPIO_OUT_ZERO);
}

static unsigned int lcm_read_id(void)
{
	int id1, id2;

	mt_set_gpio_mode(GPIO_LCD_ID1, GPIO_MODE_00);
	mt_set_gpio_mode(GPIO_LCD_ID2, GPIO_MODE_00);
	mt_set_gpio_dir(GPIO_LCD_ID1, GPIO_DIR_IN);
	mt_set_gpio_dir(GPIO_LCD_ID2, GPIO_DIR_IN);
	id1 = mt_get_gpio_in(GPIO_LCD_ID1);
	id2 = mt_get_gpio_in(GPIO_LCD_ID2);

	if (id1 == 0 && id2 == 1) {
		dprintf(CRITICAL, "[LK/LCM] st7123 WEIHUI glass (id1=%d id2=%d)\n", id1, id2);
		return LCM_ID_WEIHUI;
	}
	if (id1 == 1 && id2 == 0) {
		dprintf(CRITICAL, "[LK/LCM] st7123 HONGZHAN glass (id1=%d id2=%d)\n", id1, id2);
		return LCM_ID_HONGZHAN;
	}
	dprintf(CRITICAL, "[LK/LCM] st7123 unknown glass id1=%d id2=%d, no init sent\n", id1, id2);
	return LCM_ID_UNKNOWN;
}
#endif

static void lcm_set_util_funcs(const LCM_UTIL_FUNCS *util)
{
	memcpy(&lcm_util, util, sizeof(LCM_UTIL_FUNCS));
}

/* Values from the stock get_params (0x4c432ff4). The stock code clears the
 * whole struct first; every field not set here is zero there too. */
static void lcm_get_params(LCM_PARAMS *params)
{
	memset(params, 0, sizeof(LCM_PARAMS));

	params->type = LCM_TYPE_DSI;

	params->width = FRAME_WIDTH;
	params->height = FRAME_HEIGHT;
	params->physical_width = PHYSICAL_WIDTH;
	params->physical_height = PHYSICAL_HEIGHT;

	params->dbi.te_mode = LCM_DBI_TE_MODE_VSYNC_ONLY;
	params->dbi.te_edge_polarity = LCM_POLARITY_RISING;

	params->dsi.mode = SYNC_PULSE_VDO_MODE;
	params->dsi.LANE_NUM = LCM_FOUR_LANE;

	params->dsi.data_format.color_order = LCM_COLOR_ORDER_RGB;
	params->dsi.data_format.trans_seq = LCM_DSI_TRANS_SEQ_MSB_FIRST;
	params->dsi.data_format.padding = LCM_DSI_PADDING_ON_LSB;
	params->dsi.data_format.format = LCM_DSI_FORMAT_RGB888;

	params->dsi.PS = LCM_PACKED_PS_24BIT_RGB888;

	/* Stock timing. vtotal 1284 lines, htotal 724 pixels at PLL 177 MHz
	 * (354 Mbps per lane, 4 lanes, 24 bpp) gives about 63 Hz. The 280 line
	 * front porch is the refresh knob the dynamic refresh code adjusts. */
	params->dsi.vertical_sync_active = 4;
	params->dsi.vertical_backporch = 40;
#if defined(AYANEO_GBA)
	/* The emulators lock to the panel vsync, so rest the panel on the GBA's 59.7275 Hz instead
	 * of the stock 63.5 Hz: 81491713 / 59727.5 = 1364 lines -> vfp 360 (nominal line rate, see
	 * ddp_dsi.c AYANEO_DSI_LINE_CONST; recheck once measured on the device). */
	params->dsi.vertical_frontporch = 360;
#else
	params->dsi.vertical_frontporch = 280;
#endif
	params->dsi.vertical_active_line = FRAME_HEIGHT;

	params->dsi.horizontal_sync_active = 4;
	params->dsi.horizontal_backporch = 40;
	params->dsi.horizontal_frontporch = 40;
	params->dsi.horizontal_active_pixel = FRAME_WIDTH;

	params->dsi.PLL_CLOCK = 177;

	/* Zero in the stock LK: ssc_disable, cont_clock, noncont_clock,
	 * clk_lp_per_line_enable, esd_check_enable. The stock kernel copy adds
	 * an ESD read of 0x0A expecting 0x9C; LK does not poll ESD. */
}

static void lcm_init_lcm(void)
{
#ifdef BUILD_LK
	unsigned int id;

	dprintf(CRITICAL, "[LK/LCM] st7123p_hd640_boe lcm_init() enter\n");

	/* Stock sequence: power, 10 ms, reset high 10 ms, low 20 ms, high 120 ms. */
	lcm_gpio_output(GPIO_LCD_PWR_EN, 1);
	MDELAY(10);
	lcm_gpio_output(GPIO_LCD_RST, 1);
	MDELAY(10);
	lcm_gpio_output(GPIO_LCD_RST, 0);
	MDELAY(20);
	lcm_gpio_output(GPIO_LCD_RST, 1);
	MDELAY(120);

	id = lcm_read_id();
	if (id == LCM_ID_WEIHUI)
		push_table(lcm_init_weihui,
			   sizeof(lcm_init_weihui) / sizeof(struct LCM_setting_table), 1);
	else if (id == LCM_ID_HONGZHAN)
		push_table(lcm_init_hongzhan,
			   sizeof(lcm_init_hongzhan) / sizeof(struct LCM_setting_table), 1);
#endif
}

static void lcm_suspend(void)
{
	/* The stock LK does nothing here; the kernel owns sleep-in. */
}

static void lcm_resume(void)
{
	lcm_init_lcm();
}

LCM_DRIVER st7123p_hd640_boe_dsi_vdo_lcm_drv = {
	/*
	 * Passed to the kernel as the videolfb lcmname and MUST match the LCM
	 * driver compiled into the Konkr kernel (st7123p_hd640_boe_lcm_drv),
	 * otherwise disp_lcm_probe returns NULL and mtkfb Oopses.
	 */
	.name = "st7123p_hd640_boe_lcm_drv",
	.set_util_funcs = lcm_set_util_funcs,
	.get_params = lcm_get_params,
	.init = lcm_init_lcm,
	.suspend = lcm_suspend,
	.resume = lcm_resume,
};
