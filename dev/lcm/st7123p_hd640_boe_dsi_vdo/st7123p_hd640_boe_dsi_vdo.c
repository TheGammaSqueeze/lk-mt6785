#define FRAME_WIDTH         (640)   /* native scan: 640 columns */
#define FRAME_HEIGHT        (960)   /* 960 rows */
#define PHYSICAL_WIDTH      (50)    /* mm */
#define PHYSICAL_HEIGHT     (75)    /* mm */

#define REGFLAG_DELAY         0xFC
#define REGFLAG_END_OF_TABLE  0xFD

/* Pins as used by the stock LK; mt_set_gpio_* want the 0x80000000 flag. */
#define GPIO_LCD_PWR_EN     (14 | 0x80000000)   /* panel power enable */
#define GPIO_LCD_RST        (44 | 0x80000000)   /* panel reset */
#define GPIO_LCD_ID1        (12 | 0x80000000)   /* glass vendor id bit 1 */
#define GPIO_LCD_ID2        (13 | 0x80000000)   /* glass vendor id bit 2 */

#define LCM_ID_WEIHUI       0   /* id1 = 0, id2 = 1 */
