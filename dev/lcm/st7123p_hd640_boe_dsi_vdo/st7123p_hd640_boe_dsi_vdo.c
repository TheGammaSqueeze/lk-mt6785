/*
 * Sitronix ST7123 (BOE glass) DSI video mode panel, 640x960 native portrait,
 * mounted rotated 90 degrees as the 960x640 landscape display of the Konkr
 * Pocket Advance (MT6785, k85v1_64).
 *
 * Transcribed from the stock Konkr LK (BW03_20260730): LCM_DRIVER at RAM
 * 0x4c4b22ac, get_params 0x4c432ff4, init 0x4c433118, init tables 0x4c4b2ae4
 * (WEIHUI glass) and 0x4c4b2328 (HONGZHAN glass). Cross checked against the
 * kernel copy (drivers/misc/mediatek/lcm/st7123p_hd640_boe_dsi_vdo), which
 * carries identical geometry, porches, PLL and (for WEIHUI) a byte identical
 * init table.
 *
 * Two glass vendors ship. The stock code reads GPIO12/GPIO13 after reset and
 * picks the matching init table; with any other ID combination it sends
 * nothing. Both tables and the ID read are kept here for that reason.
 *
 * The LK frame buffer is 640 wide x 960 tall; the board uses
 * MTK_LCM_PHYSICAL_ROTATION = 90 and everything drawn for the user is rotated
 * into that buffer in software (there is no hardware rotation on this path).
 */

